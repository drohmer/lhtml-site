"""The formulas of a page kept from Jinja.

A core stage on the sources, before Jinja: a formula `\\( ... \\)` or `\\[ ... \\]`
that holds `{#` (LaTeX colors, `\\textcolor{#1f77b4}{x}`) would open a Jinja
comment, which swallows the page up to the next `#}` or fails it. Such a
formula is written between `{% raw %}` and `{% endraw %}`, so that it reaches
LHTML and KaTeX as written. The other formulas are left to Jinja: a formula
may use a variable on purpose (`\\( n = {{ params.n }} \\)`), and `{{` is
also a LaTeX group - write `{ {` for the second.

A formula already in a `{% raw %}` block of the page is left as it is (a
`{% raw %}` inside another one would close the outer block too early). The
formulas are the `math` zones of LHTML (lhtml_site/source_scan.py), so a
formula in a code block, inline code or a comment is none.
"""
import re

from lhtml_site.pages import markup
from lhtml_site.source_scan import Scan
from lhtml_site.structure import built_pages, template_path

RAW_OPEN = re.compile(r'{%-?\s*raw\s*-?%}')
RAW_CLOSE = re.compile(r'{%-?\s*endraw\s*-?%}')


def protect(text, kind='lhtml'):
    """The text, its formulas holding `{#` between {% raw %} and {% endraw %}."""
    out, position, in_raw = [], 0, False
    for zone in Scan(text, kind).zones:
        written = text[zone.start:zone.end]
        if zone.kind == 'jinja':
            if RAW_OPEN.fullmatch(written):
                in_raw = True
            elif RAW_CLOSE.fullmatch(written):
                in_raw = False
        elif zone.kind == 'math' and not in_raw and '{#' in written:
            out += [text[position:zone.start], '{% raw %}', written, '{% endraw %}']
            position = zone.end
    if not out:
        return text
    out.append(text[position:])
    return ''.join(out)


def run(meta):
    """Protect the formulas of the pages generated by this build (their copy in the site)."""
    for entry in built_pages(meta):
        path = template_path(meta, entry)
        with open(path, 'r', encoding='utf-8') as fid:
            text = fid.read()
        protected = protect(text, markup(str(path)))
        if protected != text:
            with open(path, 'w', encoding='utf-8', newline='\n') as fid:
                fid.write(protected)
